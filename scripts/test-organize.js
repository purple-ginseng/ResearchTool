#!/usr/bin/env node
// Tests for "Organize from a file": lib/organize.js (the .md / .bib parser and the matcher), with synthetic libraries.
// Pure: no workspace, no server, no network.
// Run:  node scripts/test-organize.js
const assert = require('node:assert/strict');
const org = require('../lib/organize');

const item = (id, citekey, title, fields = {}) => ({ id, citekey, fields: { title, author: 'Smith, Ann', year: '2024', ...fields } });
const ITEMS = [
  item('i1', 'ha2018world', 'Recurrent World Models Facilitate Policy Evolution', { eprint: '1809.01999', archiveprefix: 'arXiv' }),
  item('i2', 'hafner2023dreamerv3', 'Mastering Diverse Domains through World Models', { doi: '10.48550/ARXIV.2301.04104', url: 'https://arxiv.org/abs/2301.04104' }),
  item('i3', 'yuan2024tactile', '{Tactile} Representation Learning for Dexterous Manipulation', { doi: '10.1109/ICRA.2024.12345' }),
  item('i4', 'black2024pi0', 'π0: A Vision-Language-Action Flow Model for General Robot Control', { journal: 'arXiv preprint arXiv:2410.24164' }),
  item('i5', 'lee2020legged', 'Learning Quadrupedal Locomotion over Challenging Terrain', { doi: '10.1126/scirobotics.abc5986' }),
  item('i6', 'Smith2021Odd', 'A Paper with an Odd Key Capitalisation', {}),
];
const P = (text, opts = {}) => org.parse(text, { items: ITEMS, ...opts });
const names = (r) => r.groups.map((g) => g.name);
const ids = (g) => g.entries.map((e) => e.match && e.match.id);
const group = (r, name) => r.groups.find((g) => g.name === name);
let n = 0;
const t = (name, fn) => { fn(); n++; console.log('ok', name); };

// ---------- helpers ----------
t('arXiv ids in text', () => {
  assert.deepEqual(org.arxivIds('arXiv:2412.10345v2, https://arxiv.org/pdf/2401.00001v1.pdf and 2402.12345.'), ['2412.10345', '2401.00001', '2402.12345']);
  assert.deepEqual(org.arxivIds('arxiv:hep-th/9901001 10.48550/arXiv.2403.11111'), ['hep-th/9901001', '2403.11111']);
  assert.deepEqual(org.arxivIds('version 1.2 of 2024 and 12345.6789'), []);
  assert.deepEqual(org.arxivIds('10.1234/5678.12345'), []); // part of a DOI
});
t('DOIs in text', () => {
  assert.deepEqual(org.dois('see https://doi.org/10.1109/ICRA.2024.12345). And (doi:10.1000/abc).'), ['10.1109/icra.2024.12345', '10.1000/abc']);
  assert.deepEqual(org.dois('10.1000/a(b)c, more'), ['10.1000/a(b)c']);
});
t('headings are cleaned', () => {
  assert.equal(org.cleanHeading('1.2 🤖 **World** [models](http://x) :'), 'World models');
  assert.equal(org.cleanHeading('3) `Tactile` sensing'), 'Tactile sensing');
  assert.equal(org.bibHeading(' ---- World models ----'), 'World models');
  assert.equal(org.bibHeading('% Section: Tactile'), 'Tactile');
  assert.equal(org.bibHeading(' Encoding: UTF-8'), null);
  assert.equal(org.bibHeading(' ------------------'), null);
  assert.equal(org.bibHeading(' Only the entries this project cites: 12. Cite another paper and it is added.'), null);
  assert.equal(org.bibHeading(' Generated by ResearchTool - do not edit, changes are overwritten'), null);
});
t('kind from option, name, content', () => {
  assert.equal(org.detectKind('# x', 'a.bib'), 'bib');
  assert.equal(org.detectKind('@article{a, title={x}}', 'notes.md'), 'md');
  assert.equal(org.detectKind('@article{a, title={x}}', ''), 'bib');
  assert.equal(org.detectKind('# Reading\n\n- @article is a word', ''), 'md');
  assert.equal(org.detectKind('x', 'a.md', 'bib'), 'bib');
});

// ---------- .bib ----------
const BIB = `% Encoding: UTF-8

% ---------------------------------
% World models
% ---------------------------------
@article{ha2018world,
  title = {Recurrent World Models Facilitate Policy Evolution},
  year = 2018
}

@misc{other2023,
  title = {Mastering {Diverse} Domains through World Models},
  eprint = {2301.04104v1}, archivePrefix = {arXiv}
}

%% Section: Tactile sensing
@inproceedings{yuan,
  title = {Something else entirely},
  doi = {https://doi.org/10.1109/icra.2024.12345}
}
@comment{Locomotion}
@article{unknown2020,
  title = {A Paper That Is Not In The Library At All},
  author = {Nobody, N.}
}
@article{LEE2020LEGGED, title = "Learning quadrupedal locomotion"}
`;
t('.bib: comment headings, @comment headings, matching order', () => {
  const r = P(BIB, { name: 'refs.bib' });
  assert.equal(r.kind, 'bib');
  assert.deepEqual(names(r), ['World models', 'Tactile sensing', 'Locomotion']);
  const wm = group(r, 'World models');
  assert.deepEqual(ids(wm), ['i1', 'i2']);
  assert.equal(wm.entries[0].match.how, 'citekey');
  assert.equal(wm.entries[1].match.how, 'arxiv');
  assert.equal(wm.entries[1].arxiv, '2301.04104');
  assert.equal(wm.entries[0].line, 6);
  assert.ok(wm.entries[0].bibtex.startsWith('@article{ha2018world,') && wm.entries[0].bibtex.endsWith('}'));
  assert.equal(group(r, 'Tactile sensing').entries[0].match.how, 'doi');
  const loco = group(r, 'Locomotion');
  assert.equal(loco.entries[0].match, null);
  assert.match(loco.entries[0].why, /cite key unknown2020/);
  assert.equal(loco.entries[1].match.id, 'i5'); // cite key, case-blind
  assert.deepEqual(r.stats, { entries: 5, matched: 4, unmatched: 1, groups: 3 });
});
t('.bib: a cite key of another paper loses to the DOI', () => {
  const r = P('@article{ha2018world, title={x}, doi={10.1126/scirobotics.abc5986}}', { kind: 'bib' });
  assert.equal(r.groups[0].entries[0].match.id, 'i5');
  assert.equal(r.groups[0].entries[0].match.how, 'doi');
});
t('.bib: JabRef groups field wins, keywords are no group, the jabref-meta block is no heading', () => {
  const src = `% Encoding: UTF-8
% World models

@Article{ha2018world, title = {x}, groups = {Planning, World models}, keywords = {rl, wm}}
@Article{hafner2023dreamerv3, title = {y}, keywords = {World models}}

@Comment{jabref-meta: databaseType:bibtex;}
@Comment{jabref-meta: grouping:
0 AllEntriesGroup:;
1 StaticGroup:Planning\\;0\\;1\\;\\;\\;\\;;
}
`;
  const r = P(src, { name: 'library.bib' });
  assert.deepEqual(names(r), ['Planning', 'World models']);
  assert.deepEqual(ids(group(r, 'World models')), ['i2']);
});
t('.bib: no heading -> ungrouped; the header of a generated references.bib is no heading', () => {
  const r = P('% Generated by ResearchTool - do not edit, changes are overwritten\n% Only the entries this project cites: 2. Cite another paper and it is added at the next compile.\n@misc{black2024pi0, title={z}}\n', { kind: 'bib' });
  assert.deepEqual(names(r), ['']);
  assert.equal(r.groups[0].entries[0].match.id, 'i4');
});
t('.bib: CRLF and BOM', () => {
  const r = P('﻿' + BIB.replace(/\n/g, '\r\n'), { name: 'x.bib' });
  assert.deepEqual(names(r), ['World models', 'Tactile sensing', 'Locomotion']);
  assert.equal(group(r, 'World models').entries[0].line, 6);
  assert.ok(!group(r, 'World models').entries[0].raw.includes('\r'));
});
t('.bib: title match needs 12 characters', () => {
  const lib = [item('s1', 'k1', 'Short'), ...ITEMS];
  const r = org.parse('@misc{zz, title={Short}}', { items: lib, kind: 'bib' });
  assert.equal(r.groups[0].entries[0].match, null);
});

// ---------- Markdown ----------
const MD = `# Literature review

Some intro text that is not a reference.

## 1. World models 🌍

- Ha and Schmidhuber, *Recurrent World Models Facilitate Policy Evolution*, NeurIPS 2018
- [Mastering Diverse Domains through World Models](https://example.org/x)
- DreamerV3 again \\cite{hafner2023dreamerv3}

### 1.1 Tactile

* **Tactile Representation Learning for Dexterous Manipulation** - ICRA 2024
* see https://doi.org/10.1109/ICRA.2024.12345 too
* \\citep[see][p. 3]{black2024pi0, unknownkey}

## 2. Locomotion

1. [@lee2020legged; @Smith2021odd, p. 4]
2. arXiv:2410.24164
3. 10.9999/not.in.library

\`\`\`
## Not a heading
\\cite{ha2018world}
\`\`\`
`;
t('.md: nested headings, nearest heading of any level', () => {
  const r = P(MD, { name: 'review.md' });
  assert.equal(r.kind, 'md');
  assert.deepEqual(names(r), ['World models', 'Tactile', 'Locomotion']);
  assert.deepEqual(ids(group(r, 'World models')), ['i1', 'i2']); // the \cite of i2 is listed once in this group
  const tac = group(r, 'Tactile');
  assert.deepEqual(ids(tac), ['i3', 'i4', null]); // the DOI line is i3 again: once
  assert.equal(tac.entries[0].match.how, 'title');
  assert.equal(tac.entries[2].key, 'unknownkey');
  const loco = group(r, 'Locomotion');
  assert.deepEqual(ids(loco), ['i5', 'i6', 'i4', null]);
  assert.equal(loco.entries[1].match.how, 'citekey');
  assert.equal(loco.entries[3].doi, '10.9999/not.in.library');
  assert.equal(loco.entries[0].line, 19);
  assert.deepEqual(r.stats, { entries: 9, matched: 7, unmatched: 2, groups: 3 });
});
t('.md: level n = the nearest heading of level <= n', () => {
  const r = P(MD, { name: 'review.md', level: 2 });
  assert.deepEqual(names(r), ['World models', 'Locomotion']);
  assert.deepEqual(ids(group(r, 'World models')), ['i1', 'i2', 'i3', 'i4', null]);
  const r1 = P(MD, { name: 'review.md', level: 1 });
  assert.deepEqual(names(r1), ['Literature review']);
});
t('.md: a paper under two headings stays in both', () => {
  const r = P('# A\n- `ha2018world`\n# B\n- @ha2018world\n- see `notakey` and someone@ha2018world.com\n');
  assert.deepEqual(names(r), ['A', 'B']);
  assert.deepEqual(ids(group(r, 'A')), ['i1']);
  assert.deepEqual(ids(group(r, 'B')), ['i1']);
});
t('.md: keys of one line keep their order', () => {
  const r = P('- `hafner2023dreamerv3` and [@ha2018world] then \\cite{lee2020legged} and @black2024pi0\n');
  assert.deepEqual(ids(r.groups[0]), ['i2', 'i1', 'i5', 'i4']);
});
t('.md: unknown backtick / bare @ words are not entries, [@key] is', () => {
  const r = P('- `npm install` and @someone\n- [@nosuchkey]\n');
  assert.equal(r.stats.entries, 1);
  assert.equal(r.groups[0].entries[0].key, 'nosuchkey');
  assert.equal(r.groups[0].name, '');
});
t('.md: one line with two identifiers gives two entries; an arXiv link and its DOI are one', () => {
  const r = P('- https://arxiv.org/abs/2301.04104v2 (10.48550/arXiv.2301.04104) and 10.1126/scirobotics.abc5986\n');
  assert.deepEqual(ids(r.groups[0]), ['i2', 'i5']);
});
t('.md: title lines with " - ", "(" and "." endings, CRLF, BOM', () => {
  const src = '﻿## Reading\r\n\r\n- Learning Quadrupedal Locomotion over Challenging Terrain (Lee et al., 2020)\r\n- **π0: A Vision-Language-Action Flow Model for General Robot Control**. arXiv 2024\r\n- Mastering diverse domains through world models — Hafner\r\n';
  const r = P(src);
  assert.deepEqual(names(r), ['Reading']);
  assert.deepEqual(ids(r.groups[0]), ['i5', 'i4', 'i2']);
  assert.equal(r.groups[0].entries[0].line, 3);
});
t('.md: code fences (``` and ~~~) are skipped', () => {
  const r = P('# A\n~~~bibtex\n@misc{ha2018world}\n`ha2018world`\n~~~\n```\n\\cite{hafner2023dreamerv3}\n```\n');
  assert.equal(r.stats.entries, 0);
  assert.deepEqual(r.groups, []);
});
t('.md: the reading pack of this app -> one group, one entry per paper', () => {
  const pack = `# Reading pack: Proposal

2 papers, exported 2026-11-20. BibTeX: [references.bib](references.bib)

## Recurrent World Models Facilitate Policy Evolution (2018)

Smith, Ann
\`ha2018world\` · Done · cited: yes

Shows that A beats B.

- A key point (p. 3)

Note: [notes/ha2018world.md](notes/ha2018world.md)

## π0: A Vision-Language-Action Flow Model for General Robot Control (2024)

Smith, Ann
\`black2024pi0\` · To read · cited: no

`;
  const r = P(pack, { name: 'reading-list.md' });
  assert.deepEqual(names(r), ['Reading pack: Proposal']);
  assert.deepEqual(ids(r.groups[0]), ['i1', 'i4']);
  assert.equal(r.groups[0].entries[0].line, 5); // the heading
});
t('.md: an exported note (notes/<citekey>.md) stands for its own paper', () => {
  const note = '# 摘要\n\n> [!abstract]\n> Text with a [quote](#rt-page=6).\n\n# 方法论\n\nMore text.\n';
  const r = P(note, { name: 'notes/ha2018world.md' });
  assert.deepEqual(names(r), ['']);
  assert.deepEqual(ids(r.groups[0]), ['i1']);
  assert.equal(P(note, { name: 'something.md' }).stats.entries, 0);
});
t('.md: a heading that names an unmatched DOI is still a group', () => {
  const r = P('# Group 10.9999/zzz\n- `ha2018world`\n');
  assert.deepEqual(names(r), ['Group 10.9999/zzz']);
});
t('.bib: a cite key the library gave another paper is no match when the title differs', () => {
  const r = P('@inproceedings{ha2018world, title={Learning Dexterous In-Hand Rotation from Human Video}, author={Li, Wei}}', { kind: 'bib' });
  assert.equal(r.groups[0].entries[0].match, null);
  assert.match(r.groups[0].entries[0].why, /another paper/);
  // no title, the same title (or a subtitle more), the same arXiv id: the key counts
  assert.equal(P('@misc{ha2018world, note={x}}', { kind: 'bib' }).groups[0].entries[0].match.id, 'i1');
  assert.equal(P('@misc{ha2018world, title={Recurrent World Models Facilitate Policy Evolution: extended}}', { kind: 'bib' }).groups[0].entries[0].match.id, 'i1');
  assert.equal(P('@misc{hafner2023dreamerv3, title={DreamerV3}, eprint={2301.04104}}', { kind: 'bib' }).groups[0].entries[0].match.how, 'citekey');
});
t('.bib: notes, TODOs and commented-out entries are no headings', () => {
  const src = `% ---- World models ----
@article{ha2018world, title={Recurrent World Models Facilitate Policy Evolution}}

% TODO: fix the venue
@article{hafner2023dreamerv3, title={y}}
% from Google Scholar
@article{yuan2024tactile, title={z}}

% hafner2020dream, % commented out entry
%@article{old, title={Old}}

%% Locomotion
@article{lee2020legged, title={w}}
`;
  const r = P(src, { kind: 'bib' });
  assert.deepEqual(names(r), ['World models', 'Locomotion']);
  assert.deepEqual(ids(group(r, 'World models')), ['i1', 'i2', 'i3']);
  assert.equal(r.stats.entries, 4); // %@article{old} is commented out
  // without decorated headings a plain "% X" is a heading, but not when it sits right above an entry
  const plain = P('% Tactile\n\n@article{yuan2024tactile, title={z}}\n% from Google Scholar\n@article{lee2020legged, title={w}}\n', { kind: 'bib' });
  assert.deepEqual(names(plain), ['Tactile']);
});
t('.md: a heading that equals a short library title stays a group', () => {
  const lib = [item('dl', 'lecun2015deep', 'Deep learning'), item('dl2', 'x2', 'Deep Learning for Robots'), ...ITEMS];
  const r = org.parse('# Reading list\n## Classical control\n- arXiv:2301.04104\n## Deep Learning for Robots\n- arXiv:2410.24164\n', { items: lib });
  assert.deepEqual(names(r), ['Classical control', 'Deep Learning for Robots']);
  assert.deepEqual(ids(group(r, 'Deep Learning for Robots')), ['i4']);
  const r2 = org.parse('## Classical control\n- arXiv:2301.04104\n## Deep Learning\n- arXiv:2410.24164\n', { items: lib });
  assert.deepEqual(names(r2), ['Classical control', 'Deep Learning']);
});
t('.md: a reading pack with a short or missing title, and the notes.md export with counts', () => {
  const lib = [item('w', 'ha2018wm', 'World Models'), item('u', 'anon2020', ''), ...ITEMS];
  const pack = '# Reading pack: P\n\n## World Models (2018)\n\nHa, David  \n`ha2018wm` · Read · cited: no\n\n## anon2020\n\nunknown authors  \n`anon2020` · To read\n\n## π0: A Vision-Language-Action Flow Model for General Robot Control (2024)\n\nSmith  \n`black2024pi0` · Read\n';
  const r = org.parse(pack, { items: lib });
  assert.deepEqual(names(r), ['Reading pack: P']);
  assert.deepEqual(ids(r.groups[0]), ['w', 'u', 'i4']);
  const notes = '# Reading notes\n\n## World Models (2)\n\n### Recurrent World Models Facilitate Policy Evolution\n\n`ha2018world` — Ha, David (2018)\n\nTags: rl\n\n- **p.1** _contribution_ — "x"\n\n### Mastering Diverse Domains through World Models\n\n`hafner2023dreamerv3` — Hafner (2023)\n\n## Uncategorized (1)\n\n### Tactile Representation Learning for Dexterous Manipulation\n\n`yuan2024tactile` — Yuan (2024)\n';
  const n = P(notes);
  assert.deepEqual(names(n), ['World Models', '']);
  assert.deepEqual(ids(group(n, 'World Models')), ['i1', 'i2']);
  assert.deepEqual(ids(group(n, '')), ['i3']);
});
t('.md: table rows, title-only list styles, wiki links, tags, setext headings, emphasised DOIs, paper sites', () => {
  const tbl = '| Title | Topic |\n|---|---|\n| Mastering Diverse Domains through World Models | wm |\n| Learning Quadrupedal Locomotion over Challenging Terrain | legged |  |\n';
  assert.deepEqual(ids(P(tbl).groups[0]), ['i2', 'i5']);
  const styles = [
    '1. Hafner, D., Pasukonis, J. (2023). Mastering diverse domains through world models. arXiv',
    '2. Ha, D. et al. Recurrent World Models Facilitate Policy Evolution. NeurIPS 2018.',
    '3. **Learning Quadrupedal Locomotion over Challenging Terrain**, Lee et al., Sci. Robot. 2020',
    '4. Tactile Representation Learning for Dexterous Manipulation | Yuan et al. | ICRA 2024',
  ].join('\n');
  assert.deepEqual(ids(P(styles).groups[0]), ['i2', 'i1', 'i5', 'i3']);
  const wiki = '- [[ha2018world]]\n- [[hafner2023dreamerv3|DreamerV3]]\n- [[Learning Quadrupedal Locomotion over Challenging Terrain]] #toread\n';
  assert.deepEqual(ids(P(wiki).groups[0]), ['i1', 'i2', 'i5']);
  const se = '---\ntitle: notes\n---\nWorld models\n============\n- [[@ha2018world]]\n\nTactile\n---\n- **10.1109/ICRA.2024.12345**\n- [x](https://huggingface.co/papers/2410.24164)\n';
  const r = P(se);
  assert.deepEqual(names(r), ['World models', 'Tactile']);
  assert.deepEqual(ids(group(r, 'Tactile')), ['i3', 'i4']);
});
t('entry limit', () => {
  const many = Array.from({ length: org.MAX_ENTRIES + 50 }, (_, i) => `- [@k${i}]`).join('\n');
  const r = P(many);
  assert.equal(r.stats.entries, org.MAX_ENTRIES);
  assert.equal(r.stats.truncated, true);
});
t('raw is at most 200 characters', () => {
  const r = P('- `ha2018world` ' + 'x'.repeat(500));
  assert.equal(r.groups[0].entries[0].raw.length, 200);
});

t('a shortened title matches the one library title it begins', () => {
  const items = [item('m1', 'mem2026', 'Mem-World: Memory-Augmented Action-Conditioned World Models for Persistent Robot Manipulation'),
    item('w1', 'wm1', 'World Models for Robot Learning: A Survey'), item('w2', 'wm2', 'World Models for Robot Learning in the Wild')];
  const r = org.parse('# G\n- Mem-World: Memory-Augmented Action-Conditioned World Models\n- World Models for Robot Learning\n', { items });
  assert.deepEqual(r.groups[0].entries.map((e) => e.match && e.match.id), ['m1']); // the second one begins two titles: not taken for either
});

